%% Plot the saved five-matrix comparison for both input cases
% Color identifies A_i. Line style and staggered markers identify epsilon.

comparisonDir = fileparts(mfilename('fullpath'));
data = load(fullfile(comparisonDir, 'results.mat'), 'tauSet', 'relTols', 'cases');
caseNames = {'B_I5', 'B_ones5'};
xTickSteps = [2, 1];

for bIndex = 1:numel(caseNames)
    fig = plot_comparison(data.tauSet{bIndex}, ...
        data.cases(bIndex).sigmaSquared, data.relTols, xTickSteps(bIndex));
    figureName = [caseNames{bIndex} '_A1_A5_relTol_comparison'];
    savefig(fig, fullfile(comparisonDir, [figureName '.fig']));
    exportgraphics(fig, fullfile(comparisonDir, [figureName '.png']), ...
        'Resolution', 300, 'BackgroundColor', 'white');
end

function fig = plot_comparison(tau, sigmaSquared, relTols, xTickStep)
    colors = [0.0000 0.4470 0.7410; ...
              0.8500 0.3250 0.0980; ...
              0.9290 0.6940 0.1250; ...
              0.4940 0.1840 0.5560; ...
              0.4660 0.6740 0.1880];
    lineStyles = {'-.', '-', '--', ':'};
    markers = {'d', 'o', 's', '^'};
    markerOffsets = [4, 1, 2, 3];
    nA = size(sigmaSquared, 2);
    nTols = numel(relTols);
    sigmaSquared(~isfinite(sigmaSquared) | sigmaSquared <= 0) = NaN;
    positiveValues = sigmaSquared(isfinite(sigmaSquared));
    firstExponent = floor(log10(min(positiveValues)));
    lastExponent = ceil(log10(max(positiveValues)));

    fig = figure('Color', 'w', 'Units', 'pixels', ...
        'Position', [100 100 968 500]);
    ax = axes('Parent', fig, 'Position', [0.135 0.180 0.835 0.770]);
    ax.Toolbar.Visible = 'off';
    hold(ax, 'on');

    for aIndex = 1:nA
        color = colors(aIndex,:);
        for k = 1:nTols
            semilogy(ax, tau, sigmaSquared(:,aIndex,k), ...
                'Color', color, 'LineStyle', lineStyles{k}, 'LineWidth', 1.5, ...
                'Marker', markers{k}, 'MarkerSize', 5.5, ...
                'MarkerFaceColor', color, ...
                'MarkerIndices', markerOffsets(k):nTols:numel(tau), ...
                'Tag', sprintf('A%d_epsilon%d', aIndex, k));
        end
    end

    % Put the matrix colors and tolerance styles in separate legends.
    aKeys = gobjects(nA,1);
    for aIndex = 1:nA
        aKeys(aIndex) = plot(ax, NaN, NaN, '-', 'Color', colors(aIndex,:), ...
            'LineWidth', 1.5, 'DisplayName', sprintf('{\\it A}_{%d}', aIndex));
    end
    keyAxes = axes('Parent', fig, 'Position', ax.Position, ...
        'Visible', 'off', 'Color', 'none', 'PickableParts', 'none', ...
        'Tag', 'ToleranceLegendAxes');
    tolKeys = gobjects(nTols,1);
    for k = 1:nTols
        tolKeys(k) = line(keyAxes, NaN, NaN, 'Color', [0.2 0.2 0.2], ...
            'LineStyle', lineStyles{k}, 'LineWidth', 1.5, ...
            'Marker', markers{k}, 'MarkerSize', 5.5, ...
            'MarkerFaceColor', [0.2 0.2 0.2], ...
            'DisplayName', sprintf('\\epsilon = 10^{%d}', round(log10(relTols(k)))));
    end

    set(ax, 'YScale', 'log', ...
        'XLim', [0 max(tau)], 'XTick', 0:xTickStep:max(tau), ...
        'YLim', 10.^[firstExponent lastExponent], ...
        'YTick', 10.^(firstExponent:lastExponent), ...
        'FontName', 'Helvetica', 'FontSize', 20, ...
        'LineWidth', 1.1, 'TickDir', 'in', 'Box', 'on', ...
        'XGrid', 'on', 'YGrid', 'on', ...
        'XMinorGrid', 'off', 'YMinorGrid', 'on', ...
        'GridColor', [0 0 0], 'MinorGridColor', [0 0 0], ...
        'GridAlpha', 0.24, 'MinorGridAlpha', 0.16, ...
        'GridLineStyle', ':', 'MinorGridLineStyle', ':', 'Layer', 'top');
    xlabel(ax, '\tau', 'Interpreter', 'tex', 'FontSize', 22);
    ylabel(ax, '\sigma^2_{max}', 'Interpreter', 'tex', 'FontSize', 22);
    legendStyle = {'Location', 'southwest', 'Interpreter', 'tex', ...
        'FontSize', 18, 'Box', 'on', 'Color', 'w', 'EdgeColor', 'k', ...
        'AutoUpdate', 'off', 'IconColumnWidth', 34, 'LineWidth', 0.9};
    matrixLegend = legend(ax, aKeys, legendStyle{:});
    toleranceLegend = legend(keyAxes, tolKeys, legendStyle{:});
    drawnow;
    matrixPosition = matrixLegend.Position;
    tolerancePosition = toleranceLegend.Position;
    tolerancePosition(1:2) = matrixPosition(1:2) + [matrixPosition(3) + 0.009, 0];
    toleranceLegend.Position = tolerancePosition;
    fig.CurrentAxes = ax;
end
